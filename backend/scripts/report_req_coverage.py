"""Map every REQ id to the test files that reference it (BE-16 evidence).

Usage (from backend/):  uv run python scripts/report_req_coverage.py [--write PATH]

Reads the REQ ids from docs/REQUIREMENTS-TRACEABILITY.md, scans the backend,
frontend and Go test trees for each id, and prints a per-REQ table plus the
summary. A reference means a test file names the requirement; it does not by
itself prove the acceptance criteria pass, and the generated document says so.

--write PATH also writes the markdown report (docs/acceptance-records/
req-test-map.md is the intended location).
"""
from __future__ import annotations

import argparse
import io
import pathlib
import re
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
TRACEABILITY = ROOT / "docs" / "REQUIREMENTS-TRACEABILITY.md"
TEST_DIRS = (
    ROOT / "backend" / "tests",
    ROOT / "frontend" / "tests",
    ROOT / "client",
)
SUFFIXES = {".py", ".ts", ".tsx", ".cjs", ".js", ".go"}
REQ_RE = re.compile(r"REQ-[A-Z]+-\d+")
TICK = chr(96)


def _load_requirements() -> tuple[list[str], dict[str, str]]:
    text = io.open(TRACEABILITY, encoding="utf-8").read()
    ids = sorted(set(REQ_RE.findall(text)))
    statuses: dict[str, str] = {}
    for line in text.splitlines():
        if not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if not cells:
            continue
        match = REQ_RE.fullmatch(cells[0])
        if not match:
            continue
        status = cells[-1].strip("* ") if len(cells) >= 6 else ""
        if status.startswith("AT-") or status.startswith("**AT-"):
            status = ""
        statuses[match.group(0)] = status or "unmarked"
    return ids, statuses


def _iter_test_files():
    seen: set[pathlib.Path] = set()
    for base in TEST_DIRS:
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if not path.is_file() or path.suffix not in SUFFIXES:
                continue
            if "node_modules" in path.parts or ".next" in path.parts:
                continue
            if path in seen:
                continue
            seen.add(path)
            yield path


def _scan(ids: list[str]) -> dict[str, list[str]]:
    hits: dict[str, list[str]] = defaultdict(list)
    for path in _iter_test_files():
        try:
            text = io.open(path, encoding="utf-8", errors="ignore").read()
        except OSError:
            continue
        for req in ids:
            if req in text:
                hits[req].append(str(path.relative_to(ROOT)).replace("\\", "/"))
    return hits


def _group(req: str) -> str:
    return req.split("-")[1]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", type=pathlib.Path, help="write the markdown report here")
    args = parser.parse_args()

    ids, statuses = _load_requirements()
    hits = _scan(ids)
    covered = [req for req in ids if hits.get(req)]
    uncovered = [req for req in ids if not hits.get(req)]

    print(f"{'REQ':<12}{'status':<10}{'tests':>6}  first reference")
    for req in ids:
        files = hits.get(req, [])
        print(f"{req:<12}{statuses.get(req, '-'):<10}{len(files):>6}  {files[0] if files else '-'}")
    print()
    print(f"total {len(ids)}, referenced by a test {len(covered)}, not referenced {len(uncovered)}")

    if args.write:
        args.write.parent.mkdir(parents=True, exist_ok=True)
        lines = [
            "# REQ to test mapping (generated)",
            "",
            "Generated by " + TICK + "backend/scripts/report_req_coverage.py" + TICK + ". A row lists the",
            "test files that name the requirement id. A reference is **not** acceptance: it only proves",
            "a test claims the requirement. The acceptance state stays whatever the traceability table",
            "says, and the AT case still needs its own recorded run.",
            "",
            f"Total {len(ids)} REQ: {len(covered)} referenced by at least one test, {len(uncovered)} not referenced.",
            "",
            "## Not referenced by any test",
            "",
        ]
        if uncovered:
            lines += ["| REQ | traceability status |", "| --- | --- |"]
            lines += [f"| {req} | {statuses.get(req, '-')} |" for req in uncovered]
        else:
            lines.append("None.")
        for group in sorted({_group(req) for req in ids}):
            lines += ["", f"## {group}", "", "| REQ | status | tests |", "| --- | --- | --- |"]
            for req in ids:
                if _group(req) != group:
                    continue
                files = hits.get(req, [])
                cells = (
                    "<br>".join(TICK + name + TICK for name in files) if files else "-"
                )
                lines.append(f"| {req} | {statuses.get(req, '-')} | {cells} |")
        io.open(args.write, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
        print(f"wrote {args.write}")


if __name__ == "__main__":
    main()
